// Generates .env.example from each service's env definition, or with --check verifies it is
// current. Run after `pnpm build`, since it imports the compiled definitions.
import { readFileSync, writeFileSync } from 'node:fs';

const DEFINITIONS = [
  'apps/api/dist/env.js',
  'apps/worker/dist/env.js',
  'apps/mcp/dist/env.js',
  'packages/db/dist/env.js',
  'packages/db/dist/backup-env.js',
  'packages/db/dist/rotate-env.js',
];
const OUTPUT = new URL('../.env.example', import.meta.url);

const vars = new Map();
for (const file of DEFINITIONS) {
  const url = new URL(`../${file}`, import.meta.url);
  const { default: def } = await import(url.href);
  for (const [name, spec] of Object.entries(def.vars)) {
    const entry = vars.get(name) ?? { spec, services: [] };
    entry.services.push(def.service);
    vars.set(name, entry);
  }
}

const lines = [
  '# Fiscus environment variables.',
  '# Generated by `pnpm env:example` from the service definitions. Do not edit by hand.',
  '# Any variable can instead be supplied as NAME_FILE=/path/to/file (Docker/Proxmox secrets).',
];
for (const [name, { spec, services }] of vars) {
  lines.push(
    '',
    `# ${spec.description}${spec.secret ? ' (secret)' : ''}`,
    `# Used by: ${services.join(', ')}`,
  );
  lines.push(`${name}=${spec.secret ? '' : (spec.example ?? '')}`);
}
const generated = `${lines.join('\n')}\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    // Missing file is reported as out of date below.
  }
  if (current !== generated) {
    console.error(
      '.env.example is out of date. Run `pnpm build && pnpm env:example` and commit it.',
    );
    process.exit(1);
  }
  console.log('.env.example is up to date.');
} else {
  writeFileSync(OUTPUT, generated);
  console.log(`Wrote .env.example (${vars.size} variables).`);
}
